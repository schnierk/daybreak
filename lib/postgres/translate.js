'use strict';

/**
 * Übersetzt das SQL der Fachmodule in PostgreSQL. Die Module schreiben ihr SQL so, wie es
 * SQLite versteht. Damit sie nicht zweimal gepflegt werden müssen, wird es hier umgewandelt.
 *
 * Texte in Anführungszeichen werden vorher verborgen, damit keine Regel versehentlich
 * Inhalte verändert. Die Funktionen sind rein, das Ergebnis lässt sich also zwischenspeichern.
 */

const NOW_TEXT = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";

// Stellt "sqlite_master" nach, damit Module prüfen können, welche Tabellen es gibt.
const SQLITE_MASTER_VIEW = `(SELECT 'table'::text AS type, c.relname::text AS name, c.relname::text AS tbl_name,
  COALESCE((SELECT string_agg(pg_get_constraintdef(k.oid), ' ') FROM pg_constraint k WHERE k.conrelid = c.oid), '') AS sql
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = current_schema() AND c.relkind = 'r') AS sqlite_master`;

const TABLE_INFO_SQL = `SELECT a.attnum - 1 AS cid, a.attname::text AS name, format_type(a.atttypid, a.atttypmod) AS type,
  CASE WHEN a.attnotnull THEN 1 ELSE 0 END AS "notnull", pg_get_expr(d.adbin, d.adrelid) AS dflt_value,
  CASE WHEN EXISTS (SELECT 1 FROM pg_index i WHERE i.indrelid = a.attrelid AND i.indisprimary AND a.attnum = ANY(i.indkey)) THEN 1 ELSE 0 END AS pk
  FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
  WHERE a.attrelid = to_regclass($1) AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`;

const FOREIGN_KEY_LIST_SQL = `SELECT cf.relname::text AS "table", a.attname::text AS "from", af.attname::text AS "to"
  FROM pg_constraint k
  JOIN pg_class cf ON cf.oid = k.confrelid
  CROSS JOIN LATERAL unnest(k.conkey, k.confkey) AS u(attnum, fattnum)
  JOIN pg_attribute a ON a.attrelid = k.conrelid AND a.attnum = u.attnum
  JOIN pg_attribute af ON af.attrelid = k.confrelid AND af.attnum = u.fattnum
  WHERE k.contype = 'f' AND k.conrelid = to_regclass($1)`;

const REFERENCES_PATTERN = /\bREFERENCES\s+[A-Za-z0-9_]+(?:\s*\([^)]*\))?(?:\s+ON\s+(?:DELETE|UPDATE)\s+(?:CASCADE|SET\s+NULL|SET\s+DEFAULT|RESTRICT|NO\s+ACTION))*/gi;

/** Verbirgt Texte und entfernt Kommentare. */
function mask(sql) {
  const literals = [];
  let output = '';
  let index = 0;
  while (index < sql.length) {
    const character = sql[index];
    if (character === "'" || character === '"') {
      let end = index + 1;
      while (end < sql.length) {
        if (sql[end] === character) {
          if (sql[end + 1] === character) {
            end += 2;
            continue;
          }
          break;
        }
        end += 1;
      }
      literals.push(sql.slice(index, end + 1));
      output += `\u0000${literals.length - 1}\u0000`;
      index = end + 1;
    } else if (character === '-' && sql[index + 1] === '-') {
      const end = sql.indexOf('\n', index);
      index = end < 0 ? sql.length : end;
    } else if (character === '/' && sql[index + 1] === '*') {
      const end = sql.indexOf('*/', index + 2);
      index = end < 0 ? sql.length : end + 2;
    } else {
      output += character;
      index += 1;
    }
  }
  return { masked: output, literals };
}

function unmask(text, literals) {
  // eslint-disable-next-line no-control-regex
  return text.replace(/\u0000(\d+)\u0000/g, (match, index) => literals[Number(index)]);
}

function translateTypes(masked) {
  return masked
    .replace(/\bINTEGER\s+PRIMARY\s+KEY(?:\s+AUTOINCREMENT)?/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
    .replace(/\bBLOB\b/gi, 'BYTEA')
    .replace(/\s*\bWITHOUT\s+ROWID\b/gi, '')
    // Aufschiebbare Fremdschlüssel erlauben das Umziehen von Daten in beliebiger Reihenfolge.
    .replace(REFERENCES_PATTERN, match => `${match} DEFERRABLE INITIALLY IMMEDIATE`);
}

/** Ergänzt ORDER BY so, dass leere Werte wie in SQLite einsortiert werden. */
function orderNullsLikeSqlite(masked) {
  const clause = /\bORDER\s+BY\b/gi;
  let result = '';
  let last = 0;
  let match;
  while ((match = clause.exec(masked)) !== null) {
    const start = match.index + match[0].length;
    let depth = 0;
    let index = start;
    let termStart = start;
    const terms = [];
    for (; index < masked.length; index += 1) {
      const character = masked[index];
      if (character === '(') depth += 1;
      else if (character === ')') {
        if (depth === 0) break;
        depth -= 1;
      } else if (depth === 0 && character === ',') {
        terms.push(masked.slice(termStart, index));
        termStart = index + 1;
      } else if (depth === 0 && /\s/.test(character)) {
        const rest = masked.slice(index + 1, index + 12);
        if (/^(?:LIMIT|OFFSET|UNION|EXCEPT|INTERSECT|FOR|RETURNING)\b/i.test(rest)) break;
      }
    }
    terms.push(masked.slice(termStart, index));
    const rewritten = terms.map(term => {
      const trimmed = term.trim();
      if (/\bNULLS\s+(?:FIRST|LAST)\s*$/i.test(trimmed)) return trimmed;
      return /\bDESC\s*$/i.test(trimmed) ? `${trimmed} NULLS LAST` : `${trimmed} NULLS FIRST`;
    }).join(', ');
    result += `${masked.slice(last, start)} ${rewritten}`;
    last = index;
    clause.lastIndex = index;
  }
  return result + masked.slice(last);
}

function translateMasked(masked, literals) {
  let text = masked;

  // json_extract(data,'$.user.tenant') → (data::jsonb #>> '{user,tenant}')
  // eslint-disable-next-line no-control-regex
  text = text.replace(/\bjson_extract\(\s*([A-Za-z0-9_.]+)\s*,\s*\u0000(\d+)\u0000\s*\)/gi, (match, column, index) => {
    const pathParts = literals[Number(index)].replace(/^'\$\.?|'$/g, '').split('.').filter(Boolean);
    literals.push(`'{${pathParts.join(',')}}'`);
    return `(${column}::jsonb #>> \u0000${literals.length - 1}\u0000)`;
  });

  const isIgnore = /\bINSERT\s+OR\s+IGNORE\s+INTO\b/i.test(text);
  text = text.replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/gi, 'INSERT INTO');
  text = text.replace(/\bFROM\s+sqlite_master\b/gi, `FROM ${SQLITE_MASTER_VIEW}`);
  text = text.replace(/\bGROUP_CONCAT\(\s*([^(),]+?)\s*,\s*(\u0000\d+\u0000)\s*\)/gi, 'string_agg(($1)::text, $2)'); // eslint-disable-line no-control-regex
  text = text.replace(/\bGROUP_CONCAT\(\s*([^(),]+?)\s*\)/gi, "string_agg(($1)::text, ',')");
  text = text.replace(/\bdatetime\(\s*([^()]+?)\s*\)/gi, '($1)::timestamptz');
  text = text.replace(/\bIFNULL\(/gi, 'COALESCE(');
  text = text.replace(/\bCURRENT_TIMESTAMP\b/gi, NOW_TEXT);
  text = text.replace(/\bLIKE\b/gi, 'ILIKE');
  text = text.replace(/\bAS\s+INTEGER\b/gi, 'AS BIGINT').replace(/\bAS\s+REAL\b/gi, 'AS DOUBLE PRECISION');
  text = orderNullsLikeSqlite(text);

  if (isIgnore) {
    const returning = text.search(/\bRETURNING\b/i);
    text = returning >= 0
      ? `${text.slice(0, returning)}ON CONFLICT DO NOTHING ${text.slice(returning)}`
      : `${text.trimEnd()} ON CONFLICT DO NOTHING`;
  }

  let parameter = 0;
  text = text.replace(/\?/g, () => {
    parameter += 1;
    return `$${parameter}`;
  });
  return text;
}

/** Übersetzt eine einzelne Anweisung. Liefert auch, was der Adapter darüber wissen muss. */
function translateStatement(sql) {
  const trimmed = sql.trim().replace(/;\s*$/, '');

  // Der Tabellenname bleibt wie geschrieben, also auch mit Anführungszeichen; to_regclass versteht das.
  const pragma = trimmed.match(/^PRAGMA\s+([a-z_]+)\s*(?:\(\s*(.+?)\s*\)|=\s*\S+)?\s*;?$/is);
  if (pragma) {
    const name = pragma[1].toLowerCase();
    if (name === 'table_info') return { kind: 'catalog', text: TABLE_INFO_SQL, params: [pragma[2]] };
    if (name === 'foreign_key_list') return { kind: 'catalog', text: FOREIGN_KEY_LIST_SQL, params: [pragma[2]] };
    return { kind: 'noop', text: '' };
  }

  const { masked, literals } = mask(trimmed);
  // Lieber ein klarer Fehler beim Entwickeln als stilles falsches SQL.
  const unsupported = masked.match(/\?\d|(?<![\w:])@[a-z_]\w*|\bGROUP_CONCAT\(\s*DISTINCT\b|\bdatetime\([^)]*,|\bstrftime\(|\bprintf\(|\bjulianday\(/i);
  if (unsupported) throw new Error(`Diese SQL-Form wird für PostgreSQL nicht übersetzt: ${unsupported[0]}`);
  const isDdl = /^\s*(?:CREATE|ALTER|DROP)\b/i.test(masked);
  const text = translateMasked(isDdl ? translateTypes(masked) : masked, literals);
  const insert = text.match(/^\s*INSERT\s+INTO\s+([A-Za-z0-9_]+)\s*(\([^)]*\))?/i);
  return {
    kind: isDdl ? 'ddl' : insert ? 'insert' : 'statement',
    ignoresConflicts: /\bINSERT\s+OR\s+IGNORE\s+INTO\b/i.test(masked),
    text: unmask(text, literals),
    table: insert ? insert[1].toLowerCase() : null,
    columns: insert && insert[2] ? insert[2].slice(1, -1).split(',').map(column => column.trim().toLowerCase()) : null,
    hasReturning: /\bRETURNING\b/i.test(text)
  };
}

/** Übersetzt mehrere Anweisungen, wie sie db.exec bekommt. */
function translateScript(sql) {
  const { masked, literals } = mask(sql);
  return masked.split(';')
    .map(part => part.trim())
    .filter(Boolean)
    .map(part => translateStatement(unmask(part, literals)))
    .filter(statement => statement.kind !== 'noop')
    .map(statement => statement.text)
    .join(';\n');
}

const REFERENCE_TARGET = '[A-Za-z0-9_\\u0000]+(?:\\s*\\([^)]*\\))?(?:\\s+ON\\s+(?:DELETE|UPDATE)\\s+(?:CASCADE|SET\\s+NULL|SET\\s+DEFAULT|RESTRICT|NO\\s+ACTION))*';
const FOREIGN_KEY_CLAUSE = new RegExp(`,?\\s*(?:CONSTRAINT\\s+[A-Za-z0-9_\\u0000]+\\s+)?FOREIGN\\s+KEY\\s*\\([^)]*\\)\\s*REFERENCES\\s+${REFERENCE_TARGET}`, 'gi');
const INLINE_REFERENCE = new RegExp(`\\s*\\bREFERENCES\\s+${REFERENCE_TARGET}`, 'gi');

/** Entfernt Verweise aus einem CREATE TABLE. Der Umzug fügt sie erst an, wenn alle Daten da sind. */
function withoutForeignKeys(sql) {
  const { masked, literals } = mask(sql);
  return unmask(masked.replace(FOREIGN_KEY_CLAUSE, '').replace(INLINE_REFERENCE, ''), literals);
}

const statementCache = new Map();

function cachedStatement(sql) {
  let translated = statementCache.get(sql);
  if (!translated) {
    if (statementCache.size >= 5000) statementCache.clear();
    translated = translateStatement(sql);
    statementCache.set(sql, translated);
  }
  return translated;
}

module.exports = { cachedStatement, translateScript, translateStatement, withoutForeignKeys };
