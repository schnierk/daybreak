'use strict';

const assert = require('node:assert/strict');
const { test } = require('node:test');
const { translateScript, translateStatement, withoutForeignKeys } = require('../lib/postgres/translate');

const text = sql => translateStatement(sql).text;

test('Platzhalter werden nummeriert, Fragezeichen in Texten bleiben stehen', () => {
  assert.equal(text("SELECT id FROM t WHERE a=? AND b='was?' AND c=?"), "SELECT id FROM t WHERE a=$1 AND b='was?' AND c=$2");
});

test('Inhalte in Anführungszeichen werden nie verändert', () => {
  const sql = `SELECT "LIKE" FROM t WHERE note='CURRENT_TIMESTAMP LIKE INTEGER -- kein Kommentar' AND x LIKE ?`;
  assert.equal(text(sql), `SELECT "LIKE" FROM t WHERE note='CURRENT_TIMESTAMP LIKE INTEGER -- kein Kommentar' AND x ILIKE $1`);
  assert.equal(text("SELECT 'it''s ? fine' FROM t WHERE a=?"), "SELECT 'it''s ? fine' FROM t WHERE a=$1");
});

test('Kommentare werden entfernt, ihr Inhalt zählt nicht als Platzhalter', () => {
  assert.equal(text('SELECT a -- was ist das?\nFROM t /* und das? */ WHERE b=?').replace(/\s+/g, ' '), 'SELECT a FROM t WHERE b=$1');
});

test('INSERT OR IGNORE wird zu ON CONFLICT DO NOTHING, auch vor RETURNING', () => {
  const plain = translateStatement('INSERT OR IGNORE INTO t(a) VALUES(?)');
  assert.equal(plain.text, 'INSERT INTO t(a) VALUES($1) ON CONFLICT DO NOTHING');
  assert.equal(plain.ignoresConflicts, true);
  assert.equal(plain.table, 't');
  assert.deepEqual(plain.columns, ['a']);
  assert.equal(text('INSERT OR IGNORE INTO t(a) VALUES(?) RETURNING id'), 'INSERT INTO t(a) VALUES($1) ON CONFLICT DO NOTHING RETURNING id');
  assert.equal(translateStatement('INSERT INTO t(a) VALUES(?)').ignoresConflicts, false);
});

test('Datums- und Textfunktionen werden umgeschrieben', () => {
  assert.match(text('SELECT CURRENT_TIMESTAMP'), /to_char\(now\(\) AT TIME ZONE 'UTC'/);
  assert.equal(text("SELECT GROUP_CONCAT(name, ', ') n FROM t"), "SELECT string_agg((name)::text, ', ') n FROM t");
  assert.equal(text('SELECT GROUP_CONCAT(name) n FROM t'), "SELECT string_agg((name)::text, ',') n FROM t");
  assert.equal(text('SELECT IFNULL(a,0) FROM t'), 'SELECT COALESCE(a,0) FROM t');
  assert.equal(text('SELECT datetime(a) FROM t'), 'SELECT (a)::timestamptz FROM t');
  assert.equal(text("DELETE FROM s WHERE json_extract(data,'$.user.tenant')=?"), "DELETE FROM s WHERE (data::jsonb #>> '{user,tenant}')=$1");
});

test('Leere Werte werden beim Sortieren eingeordnet wie bei SQLite', () => {
  assert.equal(text('SELECT a FROM t ORDER BY a'), 'SELECT a FROM t ORDER BY a NULLS FIRST');
  assert.equal(text('SELECT a FROM t ORDER BY a DESC, b'), 'SELECT a FROM t ORDER BY a DESC NULLS LAST, b NULLS FIRST');
  assert.equal(text('SELECT a FROM t ORDER BY a DESC LIMIT ?'), 'SELECT a FROM t ORDER BY a DESC NULLS LAST LIMIT $1');
  assert.equal(text('SELECT a FROM t ORDER BY COALESCE(a, b) DESC'), 'SELECT a FROM t ORDER BY COALESCE(a, b) DESC NULLS LAST');
  assert.equal(text('SELECT * FROM (SELECT a FROM t ORDER BY a) x'), 'SELECT * FROM (SELECT a FROM t ORDER BY a NULLS FIRST) x');
});

test('Tabellendefinitionen bekommen passende Datentypen', () => {
  const ddl = text(`CREATE TABLE t (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    count INTEGER NOT NULL DEFAULT 0,
    score REAL,
    owner INTEGER REFERENCES users(id) ON DELETE CASCADE,
    created TEXT DEFAULT CURRENT_TIMESTAMP
  ) WITHOUT ROWID`);
  assert.match(ddl, /id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
  assert.match(ddl, /count BIGINT NOT NULL/);
  assert.match(ddl, /score DOUBLE PRECISION/);
  assert.match(ddl, /REFERENCES users\(id\) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE/);
  assert.doesNotMatch(ddl, /ROWID/);
});

test('PRAGMA wird zu einer Katalogabfrage oder entfällt', () => {
  assert.equal(translateStatement('PRAGMA foreign_keys = ON').kind, 'noop');
  const info = translateStatement('PRAGMA table_info(users)');
  assert.equal(info.kind, 'catalog');
  assert.deepEqual(info.params, ['users']);
  // Seltsame Namen bleiben samt Anführungszeichen ein einziger Wert und werden nie Teil des SQL.
  const odd = translateStatement('PRAGMA table_info("seltsam ""name; DROP TABLE users; --")');
  assert.deepEqual(odd.params, ['"seltsam ""name; DROP TABLE users; --"']);
  assert.doesNotMatch(odd.text, /DROP TABLE/);
  assert.equal(translateStatement('PRAGMA foreign_key_list(goals)').kind, 'catalog');
});

test('Mehrere Anweisungen werden einzeln übersetzt, Semikolons in Texten trennen nicht', () => {
  const script = translateScript("PRAGMA foreign_keys = ON; CREATE TABLE a (id INTEGER PRIMARY KEY); INSERT INTO a(note) VALUES('x;y')");
  assert.equal(script.split(';\n').length, 2);
  assert.match(script, /VALUES\('x;y'\)/);
});

test('Verweise lassen sich für den Umzug entfernen, Texte bleiben unberührt', () => {
  const sql = `CREATE TABLE t (
    id INTEGER PRIMARY KEY,
    owner INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    other INTEGER REFERENCES "seltsam" ON UPDATE SET NULL,
    note TEXT DEFAULT 'REFERENCES users(id)',
    a INTEGER,
    FOREIGN KEY (a) REFERENCES users(id) ON DELETE SET NULL
  )`;
  const stripped = withoutForeignKeys(sql).replace(/\s+/g, ' ');
  assert.equal(stripped, "CREATE TABLE t ( id INTEGER PRIMARY KEY, owner INTEGER NOT NULL, other INTEGER, note TEXT DEFAULT 'REFERENCES users(id)', a INTEGER )");
});
